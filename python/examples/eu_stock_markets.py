"""Simulate index returns from a VAR(1) fitted to EuStockMarkets data."""

import numpy as np
import randompack
import varmapack


A = np.array([
    [0.0046240972396264, -0.0957618300123132,
     0.0399411319128781, 0.0485658203952483],
    [-0.00930516507225788, -0.00717196869314693,
     0.0378105515568093, 0.0682577473923973],
    [-0.0265233470280952, -0.11365836007501,
     0.0637551035045599, 0.0915506339486754],
    [-0.0102959032743018, -0.0892451180978641,
     -0.0031969313874636, 0.164089912507651],
])
Sig = np.array([
    [0.000106041685893524, 0.0000670486580566325,
     0.0000831286412891527, 0.0000520859447746431],
    [0.0000670486580566326, 0.0000853006845924284,
     0.0000627155169059886, 0.0000427156427225213],
    [0.0000831286412891527, 0.0000627155169059886,
     0.000121206588007163, 0.0000563191801322241],
    [0.0000520859447746431, 0.0000427156427225213,
     0.0000563191801322241, 0.0000624949277411293],
])
mu = np.array([
    0.000652041747691327,
    0.000817899655305225,
    0.000437053986900166,
    0.000431985076649575,
])
last = np.array([5473.72, 7676.3, 3995, 5455])
names = ("DAX", "SMI", "CAC", "FTSE")

model = varmapack.Model(A=A, Sig=Sig, mu=mu)
rng = randompack.Rng()
rng.seed(2026)
X = model.sim(260, nrep=10, rng=rng)
final = last*np.exp(X[0].sum(axis=0))

print(f"AR spectral radius: {model.specrad():.6f}")
print("First simulated path, final synthetic index levels:")
for name, value in zip(names, final):
    print(f"  {name:<4} {value:9.2f}")
